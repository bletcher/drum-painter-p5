/**
 * Return all palettes that have exactly `n` colors.
 * Empty array if none match.
 */
export function getPalettesForCount(n) {
  return PALETTES.filter(p => p.colors.length === n);
}

/**
 * Return the list of color counts that have at least one palette.
 */
export function getAvailableColorCounts() {
  const counts = new Set(PALETTES.map(p => p.colors.length));
  return Array.from(counts).sort((a, b) => a - b);
}
